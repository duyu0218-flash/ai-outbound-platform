import { expect, test } from '@playwright/test'

// Run only against an isolated Java fixture with mock provider and synthetic data.
test('Java core campaign form, preparation, call history and stop persist', async ({ page }) => {
  test.skip(process.env.E2E_JAVA_CORE !== '1', 'requires isolated Java migration fixture')
  const auth = await page.request.post('/api/v1/auth/login', { data: { username: 'admin', password: '12345678' } })
  expect(auth.ok()).toBeTruthy()
  const headers = { Authorization: `Bearer ${(await auth.json()).access_token}` }
  const config = await page.request.get('/api/v1/admin/settings/compliance', { headers })
  expect(config.ok()).toBeTruthy()
  const compliance = (await config.json()).data
  expect((await page.request.put('/api/v1/admin/settings/compliance', { headers, data: { data: { ...compliance, allowed_start_hour: 0, allowed_end_hour: 0 } } })).ok()).toBeTruthy()
  const marker = `JavaCore-${Date.now()}`
  const phone = `139${String(Date.now()).slice(-8)}`
  const createdContact = await page.request.post('/api/v1/contacts', { headers, data: { phone, name: marker, consent_state: 'consented' } })
  expect(createdContact.ok()).toBeTruthy()

  await page.goto('/admin/login')
  await page.locator('input[autocomplete="username"]').fill('admin')
  await page.locator('input[autocomplete="current-password"]').fill('12345678')
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin\/?$/)
  await page.getByRole('menuitem', { name: /外呼任务/ }).click()
  await expect(page).toHaveURL(/\/admin\/campaigns$/)
  await page.getByRole('button', { name: /创建任务/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('名称', { exact: true }).fill(marker)
  const customers = dialog.getByLabel('选择客户', { exact: true })
  await customers.click()
  await customers.fill(marker)
  await page.locator('.ant-select-item-option-content').filter({ hasText: marker }).click()
  await customers.press('Escape')
  await expect(dialog.getByText('已选择 1 位客户')).toBeVisible()
  await expect(dialog.getByLabel('并发数', { exact: true })).toBeEnabled()
  await dialog.getByLabel('并发数', { exact: true }).fill('1')
  await dialog.getByLabel('重试次数', { exact: true }).fill('0')
  const savedResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/campaigns') && r.request().method() === 'POST')
  await dialog.getByRole('button', { name: /确.*定|OK/ }).click()
  const saved = await savedResponse
  expect(saved.ok()).toBeTruthy()
  const campaign = await saved.json()
  expect(campaign.retry_limit).toBe(0)
  await expect(dialog).toBeHidden()
  await page.reload()
  let row = page.getByRole('row').filter({ hasText: marker })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: /编\s*辑/ }).click()
  await expect(dialog.getByLabel('重试次数', { exact: true })).toHaveValue('0')
  await expect(dialog.getByText('已选择 1 位客户')).toBeVisible()
  await dialog.getByLabel('名称', { exact: true }).fill(`${marker}-edited`)
  await dialog.getByRole('button', { name: /确.*定|OK/ }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  row = page.getByRole('row').filter({ hasText: `${marker}-edited` })
  await expect(row).toBeVisible()

  // Preparation has no dial side effects; actual dispatch remains explicitly unavailable.
  const prepare = await page.request.post(`/api/v1/campaigns/${campaign.id}/start?auto_dial=false`, { headers })
  expect(prepare.ok()).toBeTruthy()
  expect((await prepare.json()).created).toBe(1)
  await page.reload()
  const startResponse = page.waitForResponse(r => r.url().includes(`/campaigns/${campaign.id}/start`) && r.request().method() === 'POST')
  await row.getByRole('button', { name: /启\s*动/ }).click()
  await page.locator('.ant-popconfirm').getByRole('button', { name: /确.*定|OK/ }).click()
  expect((await startResponse).status()).toBe(503)
  expect((await (await page.request.get(`/api/v1/campaigns/${campaign.id}`, { headers })).json()).status).toBe('prepared')

  await page.getByRole('menuitem', { name: /通话记录/ }).click()
  await expect(page).toHaveURL(/\/admin\/calls$/)
  const callRow = page.getByRole('row').filter({ hasText: phone })
  await expect(callRow).toBeVisible()
  await callRow.getByRole('button', { name: /事\s*件/ }).click()
  const drawer = page.locator('.ant-drawer')
  await expect(drawer).toBeVisible()
  await drawer.getByRole('tab', { name: '事件', exact: true }).click()
  await expect(drawer.getByRole('tabpanel', { name: '事件', exact: true }).getByText('暂无数据', { exact: true })).toBeVisible()
  await drawer.locator('.ant-drawer-close').click()
  await page.getByRole('menuitem', { name: /外呼任务/ }).click()
  await row.getByRole('button', { name: /停\s*止/ }).click()
  await page.locator('.ant-popconfirm').getByRole('button', { name: /确.*定|OK/ }).click()
  await expect(row.getByRole('button', { name: /停\s*止/ })).toHaveCount(0)
  await page.reload()
  expect((await (await page.request.get(`/api/v1/campaigns/${campaign.id}`, { headers })).json()).status).toBe('stopped')
  await page.locator('.brand').click()
  await expect(page).toHaveURL(/\/admin\/?$/)
  await page.screenshot({ path: test.info().outputPath('java-core-home.png'), fullPage: true })
})
